// A faster drop-in for makefun-site 1.0.0 (site-generator-speed-01-run-20261122).
// run(input) returns exactly makefun-site 1.0.0's build for the input, byte for byte.
// Same rules, same order, same messages — only the work is done faster:
//   - inline Markdown escapes whole plain runs at once instead of one regex per character
//   - the block lexer dispatches on the line's first character instead of testing seven regexes per line
//   - slugify has an ASCII fast path and a per-case memo; link resolution is memoised per case
//   - front matter is parsed over the file's lines once, and the body is lexed from those same lines
//     (no split/join round-trip); template `for` loops reuse one scope object per level
// Dependency-free ES module; deterministic (no clock, no environment, no randomness).
// Per-case caches are created fresh inside run(), so no case's work leaks into the next.

