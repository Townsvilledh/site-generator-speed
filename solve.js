/** A line trimmed of spaces and tabs at both ends (the line itself when there is nothing to trim). */
function trimLine(line) {
  let a = 0;
  let b = line.length;
  while (a < b && (line.charCodeAt(a) === 32 || line.charCodeAt(a) === 9)) a++;
  while (b > a && (line.charCodeAt(b - 1) === 32 || line.charCodeAt(b - 1) === 9)) b--;
  return a === 0 && b === line.length ? line : line.slice(a, b);
}

function isLangChar(c) {
  return (c >= 65 && c <= 90) || (c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 95 || c === 43 || c === 45;
}

/** A fence-opening line's language, or null: ``` + [A-Za-z0-9_+-]* + spaces/tabs only. */
function fenceOpen(line) {
  if (line.length < 3 || line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return null;
  let j = 3;
  while (j < line.length && isLangChar(line.charCodeAt(j))) j++;
  const lang = line.slice(3, j);
  while (j < line.length && (line.charCodeAt(j) === 32 || line.charCodeAt(j) === 9)) j++;
  return j === line.length ? lang : null;
}

/** Whether a line closes a fence: ``` + spaces/tabs only. */
function isFenceClose(line) {
  if (line.length < 3 || line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return false;
  for (let j = 3; j < line.length; j++) {
    const c = line.charCodeAt(j);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** A heading line's level and text, or null (a heading's text is never empty). */
function headingOf(line) {
  let n = 0;
  while (n < line.length && line.charCodeAt(n) === 35) n++;
  if (n === 0 || n > 6) return null;
  if (n >= line.length || (line.charCodeAt(n) !== 32 && line.charCodeAt(n) !== 9)) return null;
  let j = n;
  while (j < line.length && (line.charCodeAt(j) === 32 || line.charCodeAt(j) === 9)) j++;
  let end = line.length;
  while (end > j && (line.charCodeAt(end - 1) === 32 || line.charCodeAt(end - 1) === 9)) end--;
  if (end <= j) return null;
  return { depth: n, text: line.slice(j, end) };
}

/** Whether a line is a thematic break: --- or *** + spaces/tabs only. */
function isHr(line) {
  if (line.length < 3) return false;
  const c0 = line.charCodeAt(0);
  if (c0 !== 45 && c0 !== 42) return false;
  if (line.charCodeAt(1) !== c0 || line.charCodeAt(2) !== c0) return false;
  for (let j = 3; j < line.length; j++) {
    const c = line.charCodeAt(j);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** Whether `line` continues a list item: two or more spaces, then a non-whitespace character. */
function isContinued(line) {
  let i = 0;
  while (i < line.length && line.charCodeAt(i) === 32) i++;
  if (i < 2) return false;
  return i < line.length && !isWS(line.charCodeAt(i));
}

/** A list's first line: { ordered, start, text } or null. */
function listStart(line) {
  const c0 = line.charCodeAt(0);
  if ((c0 === 45 || c0 === 42) && line.charCodeAt(1) === 32) return { ordered: false, start: 1, text: line.slice(2) };
  if (c0 >= 48 && c0 <= 57) {
    let j = 0;
    while (j < line.length && j < 9 && line.charCodeAt(j) >= 48 && line.charCodeAt(j) <= 57) j++;
    if (j >= 1 && line.charCodeAt(j) === 46 && line.charCodeAt(j + 1) === 32) {
      return { ordered: true, start: Number(line.slice(0, j)), text: line.slice(j + 2) };
    }
  }
  return null;
}

/** The next item's text on `line` for a list of `ordered` kind, or null. */
function listItem(line, ordered) {
  if (!ordered) {
    const c0 = line.charCodeAt(0);
    if ((c0 === 45 || c0 === 42) && line.charCodeAt(1) === 32) return line.slice(2);
    return null;
  }
  const c0 = line.charCodeAt(0);
  if (c0 < 48 || c0 > 57) return null;
  let j = 0;
  while (j < line.length && j < 9 && line.charCodeAt(j) >= 48 && line.charCodeAt(j) <= 57) j++;
  if (j >= 1 && line.charCodeAt(j) === 46 && line.charCodeAt(j + 1) === 32) return line.slice(j + 2);
  return null;
}

/** Whether `line` ends a paragraph: a blank line, a fence, a heading or a thematic break. */
function endsParagraph(line) {
  return isBlank(line) || fenceOpen(line) !== null || headingOf(line) !== null || isHr(line);
}

/** The characters a backslash escapes, as a lookup by code unit (backslash itself is 92). */
const ESCAPABLE_CC = new Uint8Array(128);
for (const ch of ['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']) ESCAPABLE_CC[ch.charCodeAt(0)] = 1;

/** The first index from `from` where `s` holds `what` outside a backslash escape, or -1. */
function findUnescaped(s, what, from) {
  for (let j = from; j <= s.length - what.length; j++) {
    const c = s.charCodeAt(j);
    if (c === 92 && j + 1 < s.length && s.charCodeAt(j + 1) < 128 && ESCAPABLE_CC[s.charCodeAt(j + 1)] === 1) {
      j++;
      continue;
    }
    if (s.startsWith(what, j)) return j;
  }
  return -1;
}

/** The first single * from `from` (one whose run is not **), outside an escape, or -1. */
function findSingleStar(s, from) {
  for (let j = from; j < s.length; j++) {
    const c = s.charCodeAt(j);
    if (c === 92 && j + 1 < s.length && s.charCodeAt(j + 1) < 128 && ESCAPABLE_CC[s.charCodeAt(j + 1)] === 1) {
      j++;
      continue;
    }
    if (c !== 42) continue;
    if (s[j + 1] === '*') {
      j++;
      continue;
    }
    return j;
  }
  return -1;
}

/** The characters inline rendering stops at: backslash, backtick, star, bracket, and the escape table's five. */
const SPECIAL_RE = /[\\`*[&<>"']/g;

/**
 * `s` rendered inline; `env.link(target)` is a link's href. It jumps from one special character to the next
 * with one native scan instead of walking every character, and flushes each plain run through the escape
 * in a single piece. SPECIAL_RE is shared with the recursive calls, whose save/restore keeps its place.
 */
function inline(s, env) {
  let out = '';
  let plain = 0; // start of the current run of plain characters, not yet flushed
  let i = 0;
  SPECIAL_RE.lastIndex = 0;
  let m;
  while ((m = SPECIAL_RE.exec(s)) !== null) {
    const j = m.index;
    const c = s[j];
    if (c === '\\' && j + 1 < s.length && s.charCodeAt(j + 1) < 128 && ESCAPABLE_CC[s.charCodeAt(j + 1)] === 1) {
      if (j > plain) out += esc(s.slice(plain, j));
      out += esc(s[j + 1]);
      plain = i = j + 2;
      SPECIAL_RE.lastIndex = i;
      continue;
    }
    if (c === '`') {
      const k = s.indexOf('`', j + 1);
      if (k > j + 1) {
        if (j > plain) out += esc(s.slice(plain, j));
        out += `<code>${esc(s.slice(j + 1, k))}</code>`;
        plain = i = k + 1;
        SPECIAL_RE.lastIndex = i;
      } else {
        i = j + 1;
        SPECIAL_RE.lastIndex = i;
      }
      continue;
    }
    if (c === '*') {
      if (s.charCodeAt(j + 1) === 42) {
        const k = findUnescaped(s, '**', j + 2);
        if (k > j + 2) {
          if (j > plain) out += esc(s.slice(plain, j));
          const saved = SPECIAL_RE.lastIndex;
          out += `<strong>${inline(s.slice(j + 2, k), env)}</strong>`;
          SPECIAL_RE.lastIndex = saved;
          plain = i = k + 2;
          SPECIAL_RE.lastIndex = i;
        } else {
          i = j + 2;
          SPECIAL_RE.lastIndex = i;
        }
        continue;
      }
      const k = findSingleStar(s, j + 1);
      if (k > j + 1) {
        if (j > plain) out += esc(s.slice(plain, j));
        const saved = SPECIAL_RE.lastIndex;
        out += `<em>${inline(s.slice(j + 1, k), env)}</em>`;
        SPECIAL_RE.lastIndex = saved;
        plain = i = k + 1;
        SPECIAL_RE.lastIndex = i;
      } else {
        i = j + 1;
        SPECIAL_RE.lastIndex = i;
      }
      continue;
    }
    if (c === '[') {
      const k = findUnescaped(s, ']', j + 1);
      const mm = k !== -1 && s[k + 1] === '(' ? s.indexOf(')', k + 2) : -1;
      const target = mm === -1 ? '' : s.slice(k + 2, mm);
      if (target !== '' && !/\s/.test(target)) {
        if (j > plain) out += esc(s.slice(plain, j));
        const saved = SPECIAL_RE.lastIndex;
        out += `<a href="${esc(env.link(target))}">${inline(s.slice(j + 1, k), env)}</a>`;
        SPECIAL_RE.lastIndex = saved;
        plain = i = mm + 1;
        SPECIAL_RE.lastIndex = i;
        continue;
      }
      i = j + 1;
      SPECIAL_RE.lastIndex = i;
      continue;
    }
    i = j + 1;
    SPECIAL_RE.lastIndex = i;
  }
  if (s.length > plain) out += esc(s.slice(plain));
  return out;
}

/**
 * `lines` rendered: its HTML (each block on its own lines, a "\n" after the last), its table of contents
 * (every level 2 and 3 heading: level, id and its inline HTML) and its excerpt (the first paragraph's
 * inline HTML, or ""). `slugify` is the case's memoised slug function.
 */
function renderMarkdown(lines, env, slugify) {
  const ids = new Set();
  let html = '';
  const toc = [];
  let excerpt = null;
  let i = 0;
  const n = lines.length;
  while (i < n) {
    const line = lines[i];
    if (isBlank(line)) {
      i++;
      continue;
    }
    const fence = fenceOpen(line);
    if (fence !== null) {
      let body = '';
      i++;
      while (i < n && !isFenceClose(lines[i])) body += `${esc(lines[i++])}\n`;
      i++;
      const cls = fence === '' ? '' : ` class="language-${esc(fence)}"`;
      html += `<pre><code${cls}>${body}</code></pre>\n`;
      continue;
    }
    const heading = headingOf(line);
    if (heading !== null) {
      const id = uniqueSlug(slugify(heading.text), ids);
      const h = inline(heading.text, env);
      html += `<h${heading.depth} id="${id}">${h}</h${heading.depth}>\n`;
      if (heading.depth === 2 || heading.depth === 3) toc.push({ level: heading.depth, id, html: h });
      i++;
      continue;
    }
    if (isHr(line)) {
      html += '<hr>\n';
      i++;
      continue;
    }
    if (line.charCodeAt(0) === 62) {
      let body = '';
      let any = false;
      while (i < n && lines[i].charCodeAt(0) === 62) {
        const l = lines[i++];
        const t = trimLine(l.charCodeAt(1) === 32 ? l.slice(2) : l.slice(1));
        if (t !== '') {
          if (any) body += '\n';
          body += t;
          any = true;
        }
      }
      html += any ? `<blockquote>\n<p>${inline(body, env)}</p>\n</blockquote>\n` : '<blockquote>\n</blockquote>\n';
      continue;
    }
    const start = listStart(line);
    if (start !== null) {
      let itemsHtml = '';
      let item = trimLine(start.text);
      i++;
      while (i < n) {
        const m = listItem(lines[i], start.ordered);
        if (m !== null) {
          itemsHtml += `<li>${inline(item, env)}</li>\n`;
          item = trimLine(m);
          i++;
        } else if (isContinued(lines[i])) {
          item += `\n${trimLine(lines[i])}`;
          i++;
        } else break;
      }
      itemsHtml += `<li>${inline(item, env)}</li>\n`;
      const tag = start.ordered ? 'ol' : 'ul';
      const open = start.ordered && start.start !== 1 ? `<ol start="${start.start}">` : `<${tag}>`;
      html += `${open}\n${itemsHtml}</${tag}>\n`;
      continue;
    }
    let text = trimLine(line);
    i++;
    while (i < n && !endsParagraph(lines[i])) text += `\n${trimLine(lines[i++])}`;
    const p = inline(text, env);
    if (excerpt === null) excerpt = p;
    html += `<p>${p}</p>\n`;
  }
  return { html, toc, excerpt: excerpt ?? '' };
}

