const RESERVED = ['posts', 'tags', 'page'];
const byCodeUnits = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

// ---------------------------------------------------------------- text

const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
const ESC_TEST = /[&<>"']/;

/** `text` with & < > " ' escaped; unchanged when it holds none of them. */
function esc(text) {
  if (!ESC_TEST.test(text)) return text;
  return text.replace(/[&<>"']/g, (c) => ESCAPES[c]);
}

/** The slug of `text`, exactly as makefun-site's text.js computes it. */
function slugifyPlain(text) {
  let ascii = true;
  for (let i = 0; i < text.length; i++) {
    if (text.charCodeAt(i) >= 128) { ascii = false; break; }
  }
  let out = '';
  if (ascii) {
    // ASCII: NFKD is the identity and there are no combining marks, so the rule is the loop below:
    // A-Z lowered, each maximal run of other characters one '-', none at either end.
    const lower = text.toLowerCase();
    let i = 0;
    const n = lower.length;
    while (i < n) {
      let c = lower.charCodeAt(i);
      while (i < n && !((c >= 97 && c <= 122) || (c >= 48 && c <= 57))) { i++; c = i < n ? lower.charCodeAt(i) : 0; }
      if (i >= n) break;
      const start = i;
      while (i < n && ((c >= 97 && c <= 122) || (c >= 48 && c <= 57))) { i++; c = i < n ? lower.charCodeAt(i) : 0; }
      if (out !== '') out += '-';
      out += lower.slice(start, i);
    }
  } else {
    const plain = text.normalize('NFKD').replace(/\p{M}/gu, '');
    let gap = false;
    for (const ch of plain) {
      let keep = null;
      if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
      else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
      if (keep === null) { gap = out.length > 0; continue; }
      if (gap) out += '-';
      gap = false;
      out += keep;
    }
  }
  out = out.slice(0, 64).replace(/-+$/, '');
  return out === '' ? 'untitled' : out;
}

/** `slug` made unique against `taken` (and added to it). */
function uniqueSlug(slug, taken) {
  let out = slug;
  for (let n = 2; taken.has(out); n++) out = `${slug}-${n}`;
  taken.add(out);
  return out;
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

/** A YYYY-MM-DD date in words, from the string alone. */
function longDate(date) {
  const [y, m, d] = date.split('-');
  return `${Number(d)} ${MONTHS[Number(m) - 1]} ${y}`;
}

/** Whether a code unit is JavaScript whitespace (\s), as a table over the BMP. */
const WS_TABLE = new Uint8Array(65536);
for (const c of [9, 10, 11, 12, 13, 32, 160, 5760, 8192, 8193, 8194, 8195, 8196, 8197, 8198, 8199, 8200, 8201, 8202, 8232, 8233, 8239, 8287, 12288, 65279]) WS_TABLE[c] = 1;
function isWS(c) {
  return c < 65536 && WS_TABLE[c] === 1;
}

